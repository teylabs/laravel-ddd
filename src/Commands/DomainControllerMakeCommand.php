<?php

namespace Tey\LaravelDDD\Commands;

use Illuminate\Routing\Console\ControllerMakeCommand;
use Tey\LaravelDDD\Commands\Concerns\ForwardsToDomainCommands;
use Tey\LaravelDDD\Commands\Concerns\HasDomainStubs;
use Tey\LaravelDDD\Commands\Concerns\MapsRelatedKinds;
use Tey\LaravelDDD\Commands\Concerns\ResolvesDomainFromInput;
use Tey\LaravelDDD\Support\Layout\DddPlacement;
use Tey\LaravelDDD\Support\Path;
use Tey\Mod\Artifact\ResolvedArtifact;
use Tey\Mod\Commands\ControllerCommand;
use Tey\Mod\Exceptions\GenerationRefused;
use Tey\Mod\Relation\RelationResolution;

class DomainControllerMakeCommand extends ControllerCommand
{
    use ForwardsToDomainCommands,
        HasDomainStubs,
        MapsRelatedKinds,
        ResolvesDomainFromInput {
            relatedFileType as resolveRelatedFileType;
        }

    protected $name = 'ddd:controller';

    /**
     * Request names by class, as the child commands receive them.
     *
     * @var array<string, string>
     */
    protected array $forwardedRequests = [];

    /**
     * Form requests are named after the model (Store{Model}Request,
     * Update{Model}Request) and generated by ddd:request under the
     * controller's folder, exactly as before: the request's own layer
     * decides where it goes (it may differ from the controller's, e.g. a
     * custom layer), so the store-/update-request relations carry the
     * identity ddd:request will write.
     *
     * @return list<RelationResolution>
     */
    protected function plannedRelations(ResolvedArtifact $primary): array
    {
        if (! $this->option('requests') || ! $this->option('model')) {
            return [];
        }

        $model = class_basename(str_replace('/', '\\', (string) $this->option('model')));
        $resolutions = [];

        foreach ($this->layout()->relationsFrom($this->fileType()->id) as $relation) {
            if (! str_ends_with($relation->id, 'store-request') && ! str_ends_with($relation->id, 'update-request')) {
                continue;
            }

            $forwarded = $this->forwardedNameFor((str_ends_with($relation->id, 'update-request') ? 'Update' : 'Store').$model.'Request');
            $target = DddPlacement::current()->resolve('request', $this->domainBlueprint()->domain, $forwarded, str_starts_with($forwarded, '/'));
            $this->forwardedRequests[(string) $target->fqcn()] = $forwarded;
            $resolutions[] = RelationResolution::resolved($relation, $primary, $target);
        }

        return $resolutions;
    }

    /** Native request selection follows the declared edge, even when its resolved target changes layers. */
    protected function relatedFileType(string $role): string
    {
        if ($role === 'request' && ($request = $this->plannedRelation('controller-store-request')) !== null) {
            return $request->relation->toFileType;
        }

        return $this->resolveRelatedFileType($role);
    }

    /**
     * @param  array<string, mixed>  $arguments
     */
    protected function followRelation(RelationResolution $resolution, array $arguments = []): void
    {
        $name = $this->forwardedRequests[(string) $resolution->target?->fqcn()] ?? null;

        if ($name === null) {
            parent::followRelation($resolution, $arguments);

            return;
        }

        if ($this->call('ddd:request', ['name' => $name, '--domain' => $this->domainBlueprint()->domain->dotName]) !== 0) {
            throw GenerationRefused::because("Generating related request [{$name}] failed.");
        }
    }

    /**
     * A missing --model / --parent is generated as before: ddd:model with the class name.
     */
    protected function generateOwnedClass(string $fqcn, string $kindId): void
    {
        if ($this->call('make:model', ['name' => $fqcn]) !== 0) {
            throw GenerationRefused::because("Generating model [{$fqcn}] failed.");
        }
    }

    /**
     * Custom-layer controllers carry root-prefixed request relation ids.
     */
    protected function plannedRelation(string $relationId): ?RelationResolution
    {
        return parent::plannedRelation($relationId)
            ?? collect($this->currentPlan()->relations ?? [])
                ->first(fn (RelationResolution $resolution) => str_ends_with($resolution->relation->id, '-'.$relationId));
    }

    /** Resolve native placeholders from the public plan without reading the stub a second time. */
    protected function buildFormRequestReplacements(array $replace, $modelClass)
    {
        if (! $this->option('requests')) {
            return ControllerMakeCommand::buildFormRequestReplacements($replace, $modelClass);
        }

        $requestType = $this->relatedFileType('request');
        foreach ($this->currentPlan()->relations ?? [] as $resolution) {
            if ($resolution->relation->toFileType === $requestType) {
                $this->followRelation($resolution);
            }
        }

        $store = $this->plannedRelation('controller-store-request')?->target?->fqcn() ?? 'Illuminate\\Http\\Request';
        $update = $this->plannedRelation('controller-update-request')?->target?->fqcn() ?? 'Illuminate\\Http\\Request';
        $storeName = class_basename($store);
        $updateName = class_basename($update);
        $updateImport = $update;
        if ($store !== $update && strcasecmp($storeName, $updateName) === 0) {
            $updateName = 'Update'.$updateName;
            $updateImport .= ' as '.$updateName;
        }

        $imports = $store.';';
        if ($store !== $update) {
            $imports .= PHP_EOL.'use '.$updateImport.';';
        }

        return array_merge($replace, [
            '{{ storeRequest }}' => $storeName,
            '{{storeRequest}}' => $storeName,
            '{{ updateRequest }}' => $updateName,
            '{{updateRequest}}' => $updateName,
            '{{ namespacedStoreRequest }}' => $store,
            '{{namespacedStoreRequest}}' => $store,
            '{{ namespacedUpdateRequest }}' => $update,
            '{{namespacedUpdateRequest}}' => $update,
            '{{ namespacedRequests }}' => $imports,
            '{{namespacedRequests}}' => $imports,
        ]);
    }

    protected function buildClass($name)
    {
        $stub = parent::buildClass($name);

        if ($this->isUsingPublishedStub()) {
            return $stub;
        }

        // Handle Laravel 10 side effect
        // todo: deprecated since L10 is no longer supported.
        if (str($stub)->contains($invalidUse = "use {$this->getNamespace($name)}\Http\Controllers\Controller;\n")) {
            $laravel10Replacements = [
                ' extends Controller' => '',
                $invalidUse => '',
            ];

            $stub = str_replace(
                array_keys($laravel10Replacements),
                array_values($laravel10Replacements),
                $stub
            );
        }

        $replace = [];

        $appRootNamespace = $this->laravel->getNamespace();
        $pathToAppBaseController = Path::normalize(app()->path('Http/Controllers/Controller.php'));

        $baseControllerExists = $this->files->exists($pathToAppBaseController);

        if ($baseControllerExists) {
            $controllerClass = class_basename($name);
            $fullyQualifiedBaseController = "{$appRootNamespace}Http\Controllers\Controller";
            $namespaceLine = "namespace {$this->getNamespace($name)};";
            $replace["{$namespaceLine}\n"] = "{$namespaceLine}\n\nuse {$fullyQualifiedBaseController};";
            $replace["class {$controllerClass}\n"] = "class {$controllerClass} extends Controller\n";
        }

        $stub = str_replace(
            array_keys($replace),
            array_values($replace),
            $stub
        );

        return $this->sortImports($stub);
    }
}
